#!/usr/bin/env python3
"""The giants' cloud tops by latitude (PLAN-PLANETES-AAA P9 G9a) -> src/system/giant-tops.ts.

Hubble OPAL's global maps in the methane band (FQ889N, 889 nm: the higher the clouds, the brighter — less methane above
them), averaged along each degree of planetographic latitude: the zones' and belts' heights, as a profile normalised to
its own spread between 60 S and 60 N. Their details are not used: the ovals drift against one another from year to year
and the game's colour maps are of another date (in OPAL's April 2018 the Oval BA is 116 degrees west of the Great Red
Spot, 184 in the game's map). Beside it, the game's colour map's own mean linear luminance by latitude, so that the
tracer takes the map's details as heights about their latitude's mean (trace.wgsl giantHeight), the bands not counted
twice.

  python3 -I scripts/build-giant-tops.py <jupiter-fq889n.tif> <saturn-fq889n.tif>

The maps: https://archive.stsci.edu/hlsps/opal/ (cycle25/jupiter: hlsp_opal_hst_wfc3-uvis_jupiter-2018a_fq889n_v1_globalmap.tif;
cycle31/saturn: hlsp_opal_hst_wfc3-uvis_saturn-2024a_fq889n_v1_globalmap.tif) — NASA/ESA, the OPAL programme (Simon, Wong,
Orton), CC BY 4.0, doi:10.17909/T9G593.
"""
import sys
import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None
ROOT = __file__.rsplit("/scripts/", 1)[0]


def profile(img: np.ndarray) -> np.ndarray:
    """mean by degree of latitude, 181 values from 90 S to 90 N; rows without data (zero) left out, then filled from the
    nearest measured degree"""
    H = img.shape[0]
    out = np.full(181, np.nan)
    for i, lat in enumerate(range(-90, 91)):
        r0 = int(round((90 - (lat + 0.5)) * H / 180))
        r1 = int(round((90 - (lat - 0.5)) * H / 180))
        rows = img[max(r0, 0):min(max(r1, r0 + 1), H)]
        v = rows[rows > 0]
        if v.size > rows.size * 0.5:
            out[i] = v.mean()
    ok = np.where(~np.isnan(out))[0]
    for i in range(181):
        if np.isnan(out[i]):
            out[i] = out[ok[np.argmin(np.abs(ok - i))]]
    return out


def ch4(path: str) -> np.ndarray:
    p = profile(np.asarray(Image.open(path)).astype(np.float64))
    p = np.convolve(np.pad(p, 1, mode="edge"), np.ones(3) / 3, mode="valid")
    mid = p[30:151]
    # (Jupiter's polar hazes, high and bright in the band — +14 to +19 of its spread poleward of 70 degrees — capped: not
    # cloud tops, a veil far above them)
    return np.clip((p - mid.mean()) / mid.std(), -3.0, 3.0)


def lum(path: str) -> np.ndarray:
    c = np.asarray(Image.open(path).convert("RGB")).astype(np.float64) / 255.0
    lin = np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)
    y = lin @ np.array([0.2126, 0.7152, 0.0722])
    return profile(y + 1e-6)


def ts(name: str, a: np.ndarray) -> str:
    return f"  {name}: [{', '.join(f'{v:.4f}' for v in a)}],\n"


if __name__ == "__main__":
    jup, sat = sys.argv[1], sys.argv[2]
    hd = f"{ROOT}/assets/planets-hd"
    rows = [
        ("jupiterCh4", ch4(jup)),
        ("jupiterLum", lum(f"{hd}/jupiter-color.jpg")),
        ("saturnCh4", ch4(sat)),
        ("saturnLum", lum(f"{hd}/saturn-color.jpg")),
    ]
    body = "".join(ts(n, a) for n, a in rows)
    out = f"""// The giants' cloud tops by latitude (PLAN-PLANETES-AAA P9 G9a) — generated by scripts/build-giant-tops.py, do not edit.
// For each degree of planetographic latitude, 90 S to 90 N (181 values): the methane band's brightness — Hubble OPAL,
// FQ889N, Jupiter April 2018, Saturn 2024; NASA/ESA, the OPAL programme, CC BY 4.0, doi:10.17909/T9G593 —, the higher the
// clouds the brighter, normalised to its spread between 60 S and 60 N (the zones' and belts' heights, trace.wgsl
// giantHeight); and the game's colour map's mean linear luminance (its details taken about it).

export const GIANT_TOPS = {{
{body}}};

/** the table's layout in the tracer's (gpu-tables.ts TABLE_TOPS): Jupiter's methane, its luminance, Saturn's methane, its
 *  luminance — 181 values each */
export const GIANT_TOPS_TABLE = new Float32Array([
  ...GIANT_TOPS.jupiterCh4,
  ...GIANT_TOPS.jupiterLum,
  ...GIANT_TOPS.saturnCh4,
  ...GIANT_TOPS.saturnLum,
]);
"""
    open(f"{ROOT}/src/system/giant-tops.ts", "w").write(out)
    for n, a in rows:
        print(f"{n}: min {a.min():.3f} max {a.max():.3f} mean {a.mean():.3f}")
