// The CPU side's layouts of the WGSL structures, generated from the WGSL itself (docs/PLAN-J1-OPAQUE-FORWARD.md J1-0, §4 bis;
// CLAUDE.md: webgpu-utils, the first choice — the WGSL stays the one authority): each field's offset and size in floats, written as
// a TypeScript module the renderer writes its buffers by — names instead of positions (writeParams wrote ~116 of them by hand).
// At build time only: nothing of webgpu-utils in the bundle, no parse at start-up.
//
//   bun scripts/gen-layouts.ts           writes src/gen/params-layout.ts
//   bun scripts/gen-layouts.ts --check   fails if it is not up to date (tests/params-layout.test.ts runs the same check)

/** (webgpu-utils reads WebGPU's stage flags: a browser's global, given here — the specification's values) */
(globalThis as Record<string, unknown>).GPUShaderStage ??= { VERTEX: 1, FRAGMENT: 2, COMPUTE: 4 };

const ROOT = new URL("..", import.meta.url).pathname;
export const PARAMS_LAYOUT_FILE = `${ROOT}src/gen/params-layout.ts`;

/** The struct's text alone (`struct Name { … }`) from a WGSL source: the parser reads it without the rest of the module. */
export function structBlock(src: string, name: string): string {
  const i = src.indexOf(`struct ${name} {`);
  if (i < 0) throw new Error(`struct ${name} not found`);
  const j = src.indexOf("\n}", i);
  if (j < 0) throw new Error(`struct ${name}: no closing brace`);
  return src.slice(i, j + 2);
}

/** The module's text for trace.wgsl's Params: each field's offset and size in floats. */
export async function paramsLayoutSource(): Promise<string> {
  const { makeShaderDataDefinitions } = await import("webgpu-utils");
  const src = await Bun.file(`${ROOT}src/shaders/trace.wgsl`).text();
  const defs = makeShaderDataDefinitions(structBlock(src, "Params"));
  const P = defs.structs.Params!;
  const fields = P.fields as Record<string, { offset: number }>;
  const names = Object.keys(fields).sort((a, b) => fields[a]!.offset - fields[b]!.offset);
  // (a field's span: to the next one's offset — its padding with it —, the last to the struct's end)
  const span = (i: number) => ((i + 1 < names.length ? fields[names[i + 1]!]!.offset : P.size) - fields[names[i]!]!.offset) / 4;
  const off = names.map((n) => `  ${n}: ${fields[n]!.offset / 4},`).join("\n");
  const size = names.map((n, i) => `  ${n}: ${span(i)},`).join("\n");
  return `// Generated by scripts/gen-layouts.ts from src/shaders/trace.wgsl's struct Params (webgpu-utils ${await version()}): do not edit —
// run \`bun scripts/gen-layouts.ts\` after changing the struct.

/** each field's offset in the parameters' buffer [floats] (its vec4's index × 4) */
export const PARAMS = {
${off}
} as const;

/** each field's span [floats]: to the next field — its padding included */
export const PARAMS_SIZE: Record<keyof typeof PARAMS, number> = {
${size}
};

/** each field's first vec4 (its offset / 4): what renderer.writeParams's set(i, …) takes */
export const PARAMS_V4 = {
${names.map((n) => `  ${n}: ${fields[n]!.offset / 16},`).join("\n")}
} as const;

/** the struct's size [floats] */
export const PARAMS_FLOATS = ${P.size / 4};
`;
}

async function version(): Promise<string> {
  return (await Bun.file(`${ROOT}node_modules/webgpu-utils/package.json`).json()).version as string;
}

if (import.meta.main) {
  const text = await paramsLayoutSource();
  if (process.argv.includes("--check")) {
    const now = (await Bun.file(PARAMS_LAYOUT_FILE).exists()) ? await Bun.file(PARAMS_LAYOUT_FILE).text() : "";
    if (now !== text) {
      console.error("src/gen/params-layout.ts is out of date: bun scripts/gen-layouts.ts");
      process.exit(1);
    }
    console.log("gen-layouts: up to date");
  } else {
    await Bun.write(PARAMS_LAYOUT_FILE, text);
    console.log(`gen-layouts: ${PARAMS_LAYOUT_FILE}`);
  }
}
