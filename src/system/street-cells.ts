// PLAN-J8 J8-L — the streets' cells (Sam, 16 Nov 2026: « idem pour les lampadaires, charger toute la vue — et les voitures aussi »): a
// cell « rue » beside each building cell (building-cells.ts: the same z 15 key, origin and east-north frame), its street lamps and its
// main roads' pieces for the cars, prepared in workers from OpenMapTiles' z 14 roads (street-prep.ts), kept in the prepared cache
// (kerr-street-v<format>), counted in the zones and in `flightReady`. The format agreed with the render session (16 Nov, ~16:55 UTC):
// no ground in it (the far layer sets the lamps and the pieces on the relief as drawn — as Overture's buildings); the cars generated by
// the layer from the pieces (their density by class and lanes, a seed, the game's clock); the lamps' reach a parameter of the request,
// not of the format.
//
// The bytes (little-endian): a header of STREET_HEADER_BYTES, then `lampCount` lamps of LAMP_BYTES, then `pieceCount` pieces of
// PIECE_BYTES.
//   header  0 u32 magic "KSC1"   4 u16 format (STREET_FORMAT)   6 u16 reserved   8 u8 z   9..11 reserved
//          12 u32 x   16 u32 y   20 u32 lampCount   24 u32 pieceCount   28 u32 generation (the roads' source revision: YYYYMMDD)
//          32 f64 origin latitude [°]   40 f64 origin longitude [°]   48..63 reserved (0)
//   lamp    0 f32 east [m]   4 f32 north [m] (the pole's foot, in the cell's frame)   8 u16 head height [cm over the ground]
//          10 u8 road class (LAMP_CODES)   11 u8 flags (StreetFlag)
//   piece   0 f32 east a   4 f32 north a   8 f32 east b   12 f32 north b [m] (≤ PIECE_M on the ground, its middle in the cell)
//          16 u8 road class (TRAFFIC_CODES)   17 u8 flags (StreetFlag: one way along a→b, against)   18 u16 speed [cm/s]
//          20 u32 seed (the cars' phase)
import { CELL_Z } from "./building-cells";

export const STREET_FORMAT = 1;
export const STREET_MAGIC = 0x3143534b; // "KSC1"
export const STREET_HEADER_BYTES = 64;
export const LAMP_BYTES = 12;
export const PIECE_BYTES = 24;

/** the lamps' road classes on one byte (streetlamps.ts LAMP_CLASSES) */
export const LAMP_CODES = ["", "primary", "secondary", "tertiary", "minor"] as const;
/** the traffic's road classes on one byte (traffic.ts ROAD_TRAFFIC) */
export const TRAFFIC_CODES = ["", "motorway", "trunk", "primary", "secondary"] as const;

export enum StreetFlag {
  /** a lamp on the left of its street's direction (the staggered side) */
  Left = 1,
  /** a piece one way along a → b (OpenMapTiles oneway 1) */
  OnewayAlong = 2,
  /** a piece one way against it (oneway −1) */
  OnewayAgainst = 4,
}

export interface StreetLampRecord {
  east: number;
  north: number;
  /** the head's height over the ground [m] */
  height: number;
  cls: (typeof LAMP_CODES)[number];
  flags: number;
}
export interface StreetPieceRecord {
  a: [number, number];
  b: [number, number];
  cls: (typeof TRAFFIC_CODES)[number];
  flags: number;
  /** its speed [m/s] */
  speed: number;
  seed: number;
}
export interface StreetHeader {
  format: number;
  z: number;
  x: number;
  y: number;
  lampCount: number;
  pieceCount: number;
  generation: number;
  originLat: number;
  originLon: number;
}

/** A street cell's bytes. */
export function encodeStreetCell(
  h: Omit<StreetHeader, "format" | "lampCount" | "pieceCount">,
  lamps: readonly StreetLampRecord[],
  pieces: readonly StreetPieceRecord[],
): ArrayBuffer {
  const buf = new ArrayBuffer(STREET_HEADER_BYTES + lamps.length * LAMP_BYTES + pieces.length * PIECE_BYTES);
  const v = new DataView(buf);
  v.setUint32(0, STREET_MAGIC, true);
  v.setUint16(4, STREET_FORMAT, true);
  v.setUint8(8, h.z ?? CELL_Z);
  v.setUint32(12, h.x, true);
  v.setUint32(16, h.y, true);
  v.setUint32(20, lamps.length, true);
  v.setUint32(24, pieces.length, true);
  v.setUint32(28, h.generation >>> 0, true);
  v.setFloat64(32, h.originLat, true);
  v.setFloat64(40, h.originLon, true);
  let o = STREET_HEADER_BYTES;
  for (const l of lamps) {
    v.setFloat32(o, l.east, true);
    v.setFloat32(o + 4, l.north, true);
    v.setUint16(o + 8, Math.max(0, Math.min(65535, Math.round(l.height * 100))), true);
    v.setUint8(o + 10, Math.max(0, LAMP_CODES.indexOf(l.cls)));
    v.setUint8(o + 11, l.flags & 255);
    o += LAMP_BYTES;
  }
  for (const p of pieces) {
    v.setFloat32(o, p.a[0], true);
    v.setFloat32(o + 4, p.a[1], true);
    v.setFloat32(o + 8, p.b[0], true);
    v.setFloat32(o + 12, p.b[1], true);
    v.setUint8(o + 16, Math.max(0, TRAFFIC_CODES.indexOf(p.cls)));
    v.setUint8(o + 17, p.flags & 255);
    v.setUint16(o + 18, Math.max(0, Math.min(65535, Math.round(p.speed * 100))), true);
    v.setUint32(o + 20, p.seed >>> 0, true);
    o += PIECE_BYTES;
  }
  return buf;
}

/** A street cell's header, or null when the bytes are not one (magic, format, size). */
export function readStreetHeader(buf: ArrayBuffer): StreetHeader | null {
  if (buf.byteLength < STREET_HEADER_BYTES) return null;
  const v = new DataView(buf);
  if (v.getUint32(0, true) !== STREET_MAGIC || v.getUint16(4, true) !== STREET_FORMAT) return null;
  const lampCount = v.getUint32(20, true),
    pieceCount = v.getUint32(24, true);
  if (buf.byteLength !== STREET_HEADER_BYTES + lampCount * LAMP_BYTES + pieceCount * PIECE_BYTES) return null;
  return {
    format: STREET_FORMAT,
    z: v.getUint8(8),
    x: v.getUint32(12, true),
    y: v.getUint32(16, true),
    lampCount,
    pieceCount,
    generation: v.getUint32(28, true),
    originLat: v.getFloat64(32, true),
    originLon: v.getFloat64(40, true),
  };
}

/** a street cell's i-th lamp */
export function readLamp(buf: ArrayBuffer, i: number): StreetLampRecord {
  const v = new DataView(buf);
  const o = STREET_HEADER_BYTES + i * LAMP_BYTES;
  return {
    east: v.getFloat32(o, true),
    north: v.getFloat32(o + 4, true),
    height: v.getUint16(o + 8, true) / 100,
    cls: LAMP_CODES[v.getUint8(o + 10)] ?? "",
    flags: v.getUint8(o + 11),
  };
}

/** a street cell's i-th piece */
export function readPiece(buf: ArrayBuffer, i: number): StreetPieceRecord {
  const v = new DataView(buf);
  const h = readStreetHeader(buf)!;
  const o = STREET_HEADER_BYTES + h.lampCount * LAMP_BYTES + i * PIECE_BYTES;
  return {
    a: [v.getFloat32(o, true), v.getFloat32(o + 4, true)],
    b: [v.getFloat32(o + 8, true), v.getFloat32(o + 12, true)],
    cls: TRAFFIC_CODES[v.getUint8(o + 16)] ?? "",
    flags: v.getUint8(o + 17),
    speed: v.getUint16(o + 18, true) / 100,
    seed: v.getUint32(o + 20, true),
  };
}

/** the prepared streets' cache (Cache Storage): the format in its name — a new format never reads an old one's cells */
export const STREET_CACHE = `kerr-street-v${STREET_FORMAT}`;
/** a street cell's key in it (a URL: Cache Storage's keys are requests; never fetched) */
export const streetCacheUrl = (origin: string, x: number, y: number) => `${origin}/__street/${STREET_FORMAT}/${CELL_Z}/${x}/${y}.ksc`;
/** OpenMapTiles' z 14 tile a street cell is prepared from (OpenFreeMap's — scenery-sources.ts osmUrl's, built here without that module) */
export const streetRoadsUrl = (x: number, y: number) => {
  const n = 2 ** (CELL_Z - 1);
  return `https://tiles.openfreemap.org/planet/latest/${CELL_Z - 1}/${(((x >> 1) % n) + n) % n}/${y >> 1}.pbf`;
};
